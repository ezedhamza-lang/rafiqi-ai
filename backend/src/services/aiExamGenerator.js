/**
 * يولّد اختباراً بالذكاء الاصطناعي باستخدام Gemini API
 * @param {string} apiKey - مفتاح Gemini API
 * @param {string} subject - المادة
 * @param {string} gradeId - السنة
 * @param {string} trimester - الثلاثي (t1, t2, t3)
 * @returns {object} الاختبار المولد
 */
export async function generateWithAI(apiKey, subject, gradeId, trimester) {
  if (!apiKey) {
    throw new Error('مفتاح API مطلوب');
  }

  const template = QUESTION_TEMPLATES[subject]?.[gradeId]?.[trimester];
  if (!template) {
    throw new Error(`لا يوجد قالب محدد لـ ${subject}/${gradeId}/${trimester}. يمكنك استخدام قالب عام.`);
  }

  try {
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ model: 'gemini-2.0-flash' });

    const result = await model.generateContent(template);
    const response = await result.response;
    const text = response.text();

    // استخراج JSON من الاستجابة
    const jsonMatch = text.match(/\{[\s\S]*\}/);
    if (!jsonMatch) {
      throw new Error('لم يتمكن الذكاء الاصطناعي من إنتاج تنسيق JSON صالح');
    }

    const parsed = JSON.parse(jsonMatch[0]);

    // تطبيع الأسئلة
    const questions = (parsed.questions || []).map((q, idx) => ({
      id: `ai-${subject.slice(0,2)}-${gradeId.slice(-1)}-${trimester}-${Date.now()}-${idx}`,
      criteria: q.criteria,
      subCriterion: q.subCriterion,
      type: q.type || 'MCQ',
      content: q.content,
      operand1: q.operand1,
      operand2: q.operand2,
      answer: q.answer,
      options: q.options || [],
      points: q.points || 1,
      freeLines: q.freeLines || 3,
      pairs: q.pairs || [],
      coins: q.coins || [],
      source: 'ai'
    }));

    return {
      source: 'ai',
      provider: 'gemini',
      subject,
      gradeId,
      trimester,
      questions,
      totalScore: questions.reduce((sum, q) => sum + q.points, 0),
      generatedAt: new Date().toISOString()
    };

  } catch (error) {
    if (error.message.includes('API_KEY_INVALID') || error.message.includes('invalid')) {
      throw new Error('مفتاح API غير صالح. تأكد من صحته.');
    }
    throw new Error(`خطأ في الذكاء الاصطناعي: ${error.message}`);
  }
}

